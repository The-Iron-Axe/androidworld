"""Darwinian Memory Agent (DMSA) — v3 AndroidWorld Agent.

A Planner-Actor-Memory-Verifier agent that wraps the Darwinian Memory
System (arXiv:2601.22528) around an M3A-style action executor.

Architecture
------------
    DMSAgent (EnvironmentInteractingAgent)
    ├── Planner LLM callback → decomposes goal into Plan(precondition, goal)
    ├── M3A Actor → executes one action per step(), accumulating trajectory
    ├── MemoryBank → dual-factor retrieval, ϵ-mutation, risk gating
    ├── K-Verifier (K=3) → guards memory reliability
    ├── Self-Regulation → Survival-Value driven Elbow Method pruning
    └── Bayesian Risk Assessment → LCL risk score + dynamic thresholding

The agent is fully training-free — it adds evolutionary memory on top of
any MLLM without modifying model weights.
"""

